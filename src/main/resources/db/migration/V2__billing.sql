CREATE TABLE readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    period VARCHAR(7) NOT NULL,
    previous_value BIGINT NOT NULL CHECK (previous_value >= 0),
    current_value BIGINT NOT NULL CHECK (current_value > previous_value),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, period)
);

CREATE TABLE bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    reading_id BIGINT UNIQUE REFERENCES readings(id),
    period VARCHAR(7) NOT NULL,
    previous_value BIGINT NOT NULL CHECK (previous_value >= 0),
    current_value BIGINT NOT NULL CHECK (current_value > previous_value),
    tariff NUMERIC(10, 2) NOT NULL CHECK (tariff > 0),
    amount NUMERIC(16, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(10) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID', 'PAID')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, period)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES bills(id),
    amount NUMERIC(16, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(10) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX bills_owner_date ON bills(user_id, created_at);
CREATE INDEX payments_bill ON payments(bill_id);
